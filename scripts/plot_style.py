def new_figure(figsize=FIGSIZE):
    fig, ax = plt.subplots(figsize=figsize)
    return fig, ax


def value_grid(ax, axis: str) -> None:
    """Light grid on the value axis only ('x' or 'y')."""
    ax.grid(True, axis=axis, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def finish(fig, title: str, subtitle: str, path: Path) -> Path:
    """Title + subtitle top-left (subtitle wrapped to the figure width), tight layout, 300 dpi PNG."""
    lines = textwrap.wrap(subtitle, width=SUBTITLE_WRAP) or [""]
    fig.suptitle(title, x=0.012, y=0.985, ha="left", va="top", fontsize=12, fontweight="bold", color=INK)
    fig.text(0.012, 0.92, "\n".join(lines), ha="left", va="top", fontsize=10, color=INK_2, linespacing=1.3)
    fig.tight_layout(rect=(0, 0, 1, 0.885 - 0.045 * (len(lines) - 1)))
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=DPI)
    plt.close(fig)
    return path


def _luminance(hex_color: str) -> float:
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))

    def lin(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def label_ink(fill: str) -> str:
    """Text colour for a label drawn on top of `fill`: dark ink on light fills, white on dark."""
    return INK if _luminance(fill) > 0.25 else "#ffffff"


def write_readme_section(readme: Path, key: str, body: str) -> None:
    """
    Replace (or append) the block between <!-- key:start --> and
    <!-- key:end --> in results/figures/README.md, so each plot script
    owns its own section and reruns never duplicate it.
    """
    start, end = f"<!-- {key}:start -->", f"<!-- {key}:end -->"
    block = f"{start}\n{body.rstrip()}\n{end}"
    text = readme.read_text(encoding="utf-8") if readme.exists() else (
        "# Evaluation figures\n\n"
        "Generated by `scripts/plot_pipeline_eval.py` and `scripts/plot_agent4_calibration.py`. "
        "Do not edit by hand: rerun the scripts. Each caption can be pasted under the figure.\n"
    )
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    text = pattern.sub(lambda _: block, text) if pattern.search(text) else text.rstrip() + "\n\n" + block
    readme.parent.mkdir(parents=True, exist_ok=True)
    readme.write_text(text.rstrip() + "\n", encoding="utf-8")
